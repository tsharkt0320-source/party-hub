function getCho(str) {
  let res = "";
  for(let i=0; i<str.length; i++) {
    const code = str.charCodeAt(i) - 44032;
    if(code > -1 && code < 11172) res += cho[Math.floor(code / 588)];
    else res += str[i];
  }
  return res;
}

